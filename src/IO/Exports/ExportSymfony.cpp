// Symfony workflow (https://symfony.com/doc/current/workflow.html): the places
// and the transitions of the net as the YAML configuration of a workflow.
// Symfony only knows places holding a token or not: the weights, the kinds
// of arcs and the durations are lost (written as comments).

#include "IO/Exports/Exports.hpp"
#include "PetriNet/PetriNet.hpp"

#include <cctype>
#include <cerrno>
#include <cstring>
#include <fstream>
#include <map>
#include <set>
#include <sstream>

namespace tpne {

//------------------------------------------------------------------------------
//! \brief A name for Symfony: letters, digits and _ ("Wait for" -> wait_for).
static std::string symbol(std::string const& text)
{
    std::string s;
    for (char const c : text)
    {
        if (std::isalnum(static_cast<unsigned char>(c)))
            s += char(std::tolower(static_cast<unsigned char>(c)));
        else if (!s.empty() && (s.back() != '_'))
            s += '_';
    }
    while (!s.empty() && (s.back() == '_'))
        s.pop_back();
    return s;
}

//------------------------------------------------------------------------------
//! \brief Unique names of the nodes: their caption as a symbol, else their
//! key (and the key appended when two nodes have the same).
template<class Nodes>
static std::map<size_t, std::string> names(Nodes const& nodes)
{
    std::map<std::string, size_t> count;
    for (auto const& n : nodes)
        ++count[symbol(n.caption)];
    std::map<size_t, std::string> result;
    for (auto const& n : nodes)
    {
        std::string const s = symbol(n.caption);
        std::string const key = symbol(n.key);
        result[n.id] = s.empty() ? key : ((count[s] > 1u) ? s + "_" + key : s);
    }
    return result;
}

//------------------------------------------------------------------------------
std::string exportToSymfony(Net const& net, std::string const& filename)
{
    std::ofstream file(filename);
    if (!file)
    {
        std::stringstream error;
        error << "Failed to export the Petri net to '" << filename
              << "'. Reason: " << strerror(errno) << std::endl;
        return error.str();
    }

    auto const places = names(net.places());
    auto const transitions = names(net.transitions());
    std::string workflow = symbol(net.name);
    if (workflow.empty())
        workflow = "net";

    file << "# Generated by TimedPetriNetEditor from the net '" << net.name << "'.\n";
    if (features(net) != 0u)
        file << "# Symfony does not know the " << featuresToStr(features(net)) << " of the net: ignored.\n";
    if (net.type() == TypeOfNet::TimedPetriNet)
        file << "# Symfony does not know durations: ignored.\n";
    file << "framework:\n"
         << "    workflows:\n"
         << "        " << workflow << ":\n"
         << "            type: 'workflow'\n"
         << "            audit_trail:\n"
         << "                enabled: true\n"
         << "            marking_store:\n"
         << "                type: 'method'\n"
         << "                property: 'currentPlace'\n"
         << "            supports:\n"
         << "                - App\\Entity\\" << char(std::toupper(static_cast<unsigned char>(workflow[0])))
         << workflow.substr(1u) << "\n"
         << "            initial_marking:";
    bool marked = false;
    for (auto const& p : net.places())
    {
        if (p.tokens > 0u)
        {
            file << "\n                - '" << places.at(p.id) << "'";
            marked = true;
        }
    }
    file << (marked ? "\n" : " []\n");

    file << "            places:\n";
    for (auto const& p : net.places())
        file << "                - '" << places.at(p.id) << "'\n";

    file << "            transitions:\n";
    for (auto const& t : net.transitions())
    {
        file << "                '" << transitions.at(t.id) << "':\n"
             << "                    from:";
        if (net.arcsIn(t).empty())
            file << " []";
        for (auto const& a : net.arcsIn(t))
            file << "\n                        - '" << places.at(a.from.id) << "'";
        file << "\n                    to:";
        if (net.arcsOut(t).empty())
            file << " []";
        for (auto const& a : net.arcsOut(t))
            file << "\n                        - '" << places.at(a.to.id) << "'";
        file << "\n";
    }
    return {};
}

} // namespace tpne
