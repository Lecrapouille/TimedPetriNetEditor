// LaTeX (TikZ, library petri): a standalone document drawing the net at the
// positions of the editor (pdflatex net.tex). Places with their tokens,
// transitions, arcs with their weight, duration (timed nets) and color;
// inhibitor arcs end with a circle, reset arcs with a double arrow.

#include "IO/Exports/Exports.hpp"
#include "PetriNet/PetriNet.hpp"

#include <cerrno>
#include <cstring>
#include <fstream>
#include <iomanip>
#include <sstream>

namespace tpne {

//! \brief Centimeters per pixel of the editor: a net of 800 pixels is 16 cm.
static float const SCALE = 0.02f;

//------------------------------------------------------------------------------
//! \brief The text escaped for LaTeX (text mode).
static std::string latex(std::string const& text)
{
    std::string s;
    for (char const c : text)
    {
        switch (c)
        {
        case '\\': s += "\\textbackslash{}"; break;
        case '&': case '%': case '$': case '#': case '_': case '{': case '}':
            s += '\\'; s += c; break;
        case '~': s += "\\textasciitilde{}"; break;
        case '^': s += "\\textasciicircum{}"; break;
        default: s += c; break;
        }
    }
    return s;
}

//------------------------------------------------------------------------------
static std::string coordinates(Point const& p)
{
    std::ostringstream os;
    os << std::fixed << std::setprecision(2) << (p.x * SCALE) << ", " << (-p.y * SCALE);
    return "(" + os.str() + ")";
}

//------------------------------------------------------------------------------
std::string exportToPetriLaTeX(Net const& net, std::string const& filename)
{
    std::ofstream file(filename);
    if (!file)
    {
        std::stringstream error;
        error << "Failed to export the Petri net to '" << filename
              << "'. Reason: " << strerror(errno) << std::endl;
        return error.str();
    }

    bool const timed = (net.type() == TypeOfNet::TimedPetriNet);
    file << "% Generated by TimedPetriNetEditor from the net '" << net.name << "'.\n"
         << "\\documentclass[border=0.2cm]{standalone}\n"
         << "\\usepackage{tikz}\n"
         << "\\usetikzlibrary{petri,arrows.meta}\n"
         << "\\begin{document}\n"
         << "\\begin{tikzpicture}[\n"
         << "  every place/.style={draw=blue!75, fill=blue!10, minimum size=7mm, thick},\n"
         << "  every transition/.style={draw=black, fill=black!70, minimum width=6mm, minimum height=2mm},\n"
         << "  every label/.style={font=\\small},\n"
         << "  arc/.style={-{Latex}, thick},\n"
         << "  inhibitor/.style={-{Circle[open]}, thick},\n"
         << "  reset/.style={-{Latex}{Latex}, thick, dashed}]\n";

    file << "\n% Places\n";
    for (auto const& p : net.places())
    {
        file << "\\node[place, label=below:{" << latex(p.caption.empty() ? p.key : p.caption) << "}";
        // The petri library draws up to 4 tokens, the number beyond.
        if ((p.tokens > 0u) && (p.tokens <= 4u))
            file << ", tokens=" << p.tokens;
        file << "] (" << p.key << ") at " << coordinates(net.position(p)) << " {";
        if (p.tokens > 4u)
            file << p.tokens;
        file << "};\n";
    }

    file << "\n% Transitions\n";
    for (auto const& t : net.transitions())
    {
        file << "\\node[transition, label=above:{" << latex(t.caption.empty() ? t.key : t.caption) << "}] ("
             << t.key << ") at " << coordinates(net.position(t)) << " {};\n";
    }

    file << "\n% Arcs\n";
    for (auto const& a : net.arcs())
    {
        std::string label;
        if (a.weight != 1u)
            label = std::to_string(a.weight);
        if (timed && a.from.isTransition() && (a.durationOrZero() != 0.0f))
        {
            std::ostringstream d;
            d << a.durationOrZero();
            label += (label.empty() ? "" : ", ") + d.str() + "\\,s";
        }
        if (a.color != AnyColor)
            label += (label.empty() ? "" : ", ") + latex(net.colors.name(a.color));
        char const* style = (a.kind == ArcKind::Inhibitor) ? "inhibitor"
                          : (a.kind == ArcKind::Reset) ? "reset" : "arc";
        file << "\\draw[" << style << "] (" << a.from.key() << ") -- ";
        if (!label.empty())
            file << "node[midway, above, sloped, font=\\small] {" << label << "} ";
        file << "(" << a.to.key() << ");\n";
    }

    file << "\\end{tikzpicture}\n\\end{document}\n";
    return {};
}

} // namespace tpne
