// SVG: a picture of the net at the positions of the editor, for documents and
// web pages. Places are circles with their tokens (GRAFCET: steps, double for
// the initial ones), transitions rectangles; the arcs show their weight, their
// duration and their color, inhibitor arcs end with a circle. A timed event
// graph drawn compactly keeps its places on its arcs.

#include "IO/Exports/Exports.hpp"
#include "PetriNet/PetriNet.hpp"

#include <algorithm>
#include <cerrno>
#include <cmath>
#include <cstring>
#include <fstream>
#include <limits>
#include <sstream>

namespace tpne {

namespace {

constexpr float PLACE_RADIUS = 18.0f;
constexpr float TRANS_WIDTH = 36.0f;
constexpr float TRANS_HEIGHT = 10.0f;
constexpr float STEP_SIZE = 34.0f;

std::string xml(std::string const& text)
{
    std::string s;
    for (char const c : text)
    {
        switch (c)
        {
        case '&': s += "&amp;"; break;
        case '<': s += "&lt;"; break;
        case '>': s += "&gt;"; break;
        case '"': s += "&quot;"; break;
        default: s += c; break;
        }
    }
    return s;
}

std::string number(float const value)
{
    std::ostringstream os;
    os << std::round(value * 100.0f) / 100.0f;
    return os.str();
}

//! \brief Point on the border of the node, toward the point p.
Point border(Net const& net, Node const& node, Point const& p)
{
    Point const c = net.position(node);
    float const dx = p.x - c.x;
    float const dy = p.y - c.y;
    float const d = std::max(1e-3f, std::sqrt(dx * dx + dy * dy));
    if (node.type == Node::Type::Place)
    {
        float const r = (net.type() == TypeOfNet::GRAFCET) ? STEP_SIZE * 0.5f : PLACE_RADIUS;
        return { c.x + dx / d * r, c.y + dy / d * r };
    }
    // Rectangle: the side the line crosses.
    float const hw = TRANS_WIDTH * 0.5f;
    float const hh = TRANS_HEIGHT * 0.5f;
    float const t = std::min(hw / std::max(1e-3f, std::fabs(dx)), hh / std::max(1e-3f, std::fabs(dy)));
    return { c.x + dx * t, c.y + dy * t };
}

} // namespace

//------------------------------------------------------------------------------
std::string exportToSVG(Net const& net, std::string const& filename)
{
    std::ofstream file(filename);
    if (!file)
    {
        std::stringstream error;
        error << "Failed to export the Petri net to '" << filename
              << "'. Reason: " << strerror(errno) << std::endl;
        return error.str();
    }

    bool const grafcet = (net.type() == TypeOfNet::GRAFCET);
    bool const timed = (net.type() == TypeOfNet::TimedPetriNet);
    bool const compact = net.layout().compact;

    // Size of the picture: the nodes, room for their captions.
    float x0 = std::numeric_limits<float>::max(), y0 = x0;
    float x1 = std::numeric_limits<float>::lowest(), y1 = x1;
    auto extend = [&](Point const& p) {
        x0 = std::min(x0, p.x - 70.0f); y0 = std::min(y0, p.y - 40.0f);
        x1 = std::max(x1, p.x + 70.0f); y1 = std::max(y1, p.y + 45.0f);
    };
    for (auto const& p : net.places())
        if (!compact) extend(net.position(p));
    for (auto const& t : net.transitions())
        extend(net.position(t));
    if (x0 > x1)
    {
        x0 = y0 = 0.0f;
        x1 = y1 = 100.0f;
    }

    file << "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n"
         << "<!-- Generated by TimedPetriNetEditor from the net '" << xml(net.name) << "'. -->\n"
         << "<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"" << number(x0) << " " << number(y0) << " "
         << number(x1 - x0) << " " << number(y1 - y0) << "\" width=\"" << number(x1 - x0)
         << "\" height=\"" << number(y1 - y0) << "\" font-family=\"Helvetica, Arial, sans-serif\" font-size=\"12\">\n"
         << "  <title>" << xml(net.name) << "</title>\n"
         << "  <defs>\n"
         << "    <marker id=\"arrow\" viewBox=\"0 0 10 10\" refX=\"10\" refY=\"5\" markerWidth=\"8\" markerHeight=\"8\" orient=\"auto-start-reverse\">"
         << "<path d=\"M 0 0 L 10 5 L 0 10 z\" fill=\"#37474f\"/></marker>\n"
         << "    <marker id=\"circle\" viewBox=\"0 0 10 10\" refX=\"10\" refY=\"5\" markerWidth=\"8\" markerHeight=\"8\">"
         << "<circle cx=\"5\" cy=\"5\" r=\"4\" fill=\"white\" stroke=\"#37474f\" stroke-width=\"1.5\"/></marker>\n"
         << "  </defs>\n"
         << "  <rect x=\"" << number(x0) << "\" y=\"" << number(y0) << "\" width=\"" << number(x1 - x0)
         << "\" height=\"" << number(y1 - y0) << "\" fill=\"white\"/>\n";

    // Arcs, under the nodes.
    file << "  <g stroke=\"#37474f\" stroke-width=\"1.5\" fill=\"none\">\n";
    for (auto const& a : net.arcs())
    {
        Node const* from = &net.node(a.from);
        Node const* to = &net.node(a.to);
        size_t tokens = 0u;
        if (compact)
        {
            // Transition -> place -> transition drawn as one arc.
            if (a.from.isPlace())
                continue;
            auto const next = net.arcsOut(*to);
            if (next.empty())
                continue;
            tokens = net.node(a.to).type == Node::Type::Place ? net.places()[a.to.id].tokens : 0u;
            to = &net.node(next.front().to);
        }
        Point const p = border(net, *from, net.position(*to));
        Point const q = border(net, *to, net.position(*from));
        file << "    <line x1=\"" << number(p.x) << "\" y1=\"" << number(p.y) << "\" x2=\"" << number(q.x)
             << "\" y2=\"" << number(q.y) << "\"";
        if (a.kind == ArcKind::Inhibitor)
            file << " marker-end=\"url(#circle)\"";
        else if (!grafcet)
            file << " marker-end=\"url(#arrow)\"";
        if (a.kind == ArcKind::Reset)
            file << " stroke-dasharray=\"5,3\"";
        file << "/>\n";

        // Labels in the middle: weight, duration, color; tokens of a compact
        // event graph near the start.
        std::string label;
        if (a.weight != 1u)
            label = std::to_string(a.weight);
        if (timed && a.from.isTransition() && (a.durationOrZero() != 0.0f))
            label += (label.empty() ? "" : ", ") + number(a.durationOrZero());
        if (a.color != AnyColor)
            label += (label.empty() ? "" : ", ") + net.colors.name(a.color);
        if (!label.empty())
        {
            file << "    <text x=\"" << number((p.x + q.x) * 0.5f + 4.0f) << "\" y=\"" << number((p.y + q.y) * 0.5f - 4.0f)
                 << "\" stroke=\"none\" fill=\"#1565c0\">" << xml(label) << "</text>\n";
        }
        if (tokens > 0u)
        {
            Point const m = { p.x + (q.x - p.x) * 0.2f, p.y + (q.y - p.y) * 0.2f };
            file << "    <circle cx=\"" << number(m.x) << "\" cy=\"" << number(m.y) << "\" r=\"4\" fill=\"#263238\" stroke=\"none\"/>\n";
            if (tokens > 1u)
                file << "    <text x=\"" << number(m.x + 6.0f) << "\" y=\"" << number(m.y - 6.0f)
                     << "\" stroke=\"none\" fill=\"#263238\">" << tokens << "</text>\n";
        }
    }
    file << "  </g>\n";

    // Places (steps of a GRAFCET).
    file << "  <g stroke=\"#37474f\" stroke-width=\"1.5\">\n";
    for (auto const& p : net.places())
    {
        if (compact)
            break;
        Point const c = net.position(p);
        std::string const caption = p.caption.empty() ? p.key : p.caption;
        if (grafcet)
        {
            float const h = STEP_SIZE * 0.5f;
            file << "    <rect x=\"" << number(c.x - h) << "\" y=\"" << number(c.y - h) << "\" width=\"" << STEP_SIZE
                 << "\" height=\"" << STEP_SIZE << "\" fill=\"" << (p.tokens ? "#c8e6c9" : "white") << "\"/>\n";
            if (p.tokens > 0u)
                file << "    <rect x=\"" << number(c.x - h + 3.0f) << "\" y=\"" << number(c.y - h + 3.0f) << "\" width=\""
                     << (STEP_SIZE - 6.0f) << "\" height=\"" << (STEP_SIZE - 6.0f) << "\" fill=\"none\"/>\n";
            file << "    <text x=\"" << number(c.x) << "\" y=\"" << number(c.y + 4.0f)
                 << "\" text-anchor=\"middle\" stroke=\"none\" fill=\"#263238\">" << p.id << "</text>\n";
        }
        else
        {
            file << "    <circle cx=\"" << number(c.x) << "\" cy=\"" << number(c.y) << "\" r=\"" << PLACE_RADIUS
                 << "\" fill=\"white\"/>\n";
            if ((p.tokens > 0u) && (p.tokens <= 4u))
            {
                // Tokens as dots, around the center.
                for (size_t k = 0u; k < p.tokens; ++k)
                {
                    float const angle = 6.2831853f * float(k) / float(p.tokens);
                    float const r = (p.tokens == 1u) ? 0.0f : 6.0f;
                    file << "    <circle cx=\"" << number(c.x + r * std::cos(angle)) << "\" cy=\""
                         << number(c.y + r * std::sin(angle)) << "\" r=\"3.5\" fill=\"#263238\" stroke=\"none\"/>\n";
                }
            }
            else if (p.tokens > 4u)
            {
                file << "    <text x=\"" << number(c.x) << "\" y=\"" << number(c.y + 4.0f)
                     << "\" text-anchor=\"middle\" stroke=\"none\" fill=\"#263238\">" << p.tokens << "</text>\n";
            }
        }
        file << "    <text x=\"" << number(c.x) << "\" y=\"" << number(c.y + PLACE_RADIUS + 15.0f)
             << "\" text-anchor=\"middle\" stroke=\"none\" fill=\"#263238\">" << xml(caption) << "</text>\n";
    }

    // Transitions (receptivities of a GRAFCET on their right).
    for (auto const& t : net.transitions())
    {
        Point const c = net.position(t);
        std::string const caption = t.caption.empty() ? t.key : t.caption;
        file << "    <rect x=\"" << number(c.x - TRANS_WIDTH * 0.5f) << "\" y=\"" << number(c.y - TRANS_HEIGHT * 0.5f)
             << "\" width=\"" << TRANS_WIDTH << "\" height=\"" << TRANS_HEIGHT << "\" rx=\"2\" fill=\"#455a64\"/>\n";
        if (grafcet)
            file << "    <text x=\"" << number(c.x + TRANS_WIDTH * 0.5f + 6.0f) << "\" y=\"" << number(c.y + 4.0f)
                 << "\" stroke=\"none\" fill=\"#263238\">" << xml(caption) << "</text>\n";
        else
            file << "    <text x=\"" << number(c.x) << "\" y=\"" << number(c.y + TRANS_HEIGHT + 12.0f)
                 << "\" text-anchor=\"middle\" stroke=\"none\" fill=\"#263238\">" << xml(caption) << "</text>\n";
    }
    file << "  </g>\n</svg>\n";
    return {};
}

} // namespace tpne
